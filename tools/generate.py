"""Deterministic UML/Java forward engineering from the editable model."""
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
MODEL = json.loads((ROOT / 'model/university.json').read_text())
HEADER = '''@startuml
!pragma layout smetana
skinparam classAttributeIconSize 0
skinparam shadowing false
skinparam defaultFontName SansSerif
skinparam packageStyle rectangle
skinparam classBackgroundColor #F1F5FF
'''

def uml_member(signature):
    visibility = '+' if signature.startswith('public ') else '#' if signature.startswith('protected ') else '~'
    return visibility + re.sub(r'^(public|protected|private) ', '', signature)

def main():
    output = ROOT / 'src/main/java' / MODEL['package'].replace('.', '/')
    output.mkdir(parents=True, exist_ok=True)
    diagram = [HEADER, 'title Университетская информационная система — модель классов\n']
    for c in MODEL['classes']:
        declaration = ('public abstract class ' if c['abstract'] else 'public class ') + c['name']
        if c['parent']:
            declaration += ' extends ' + c['parent']
        lines = ['// Generated by tools/generate.py from model/university.json. Edit the model.',
                 'package ' + MODEL['package'] + ';', '', 'import java.util.*;', 'import java.time.LocalDate;', '', declaration + ' {']
        lines += ['    ' + f + ';' for f in c['fields']]
        for m in c['methods']:
            lines += ['', '    ' + m['signature'] + ' {']
            lines += ['        ' + line for line in m['body'].splitlines()]
            lines += ['    }']
        lines += ['}', '']
        (output / (c['name'] + '.java')).write_text('\n'.join(lines))
        diagram.append(('abstract class ' if c['abstract'] else 'class ') + c['name'] + ' {')
        diagram += ['  -' + f.removeprefix('private ').split(' = ')[0] for f in c['fields']]
        diagram += ['  ' + uml_member(m['signature']) for m in c['methods']]
        diagram.append('}')
        if c['parent']:
            diagram.append(c['parent'] + ' <|-- ' + c['name'])
    diagram += ['class App <<boundary>> {', '  +void assignCourse()', '  +void run()', '  +void main(String[] args) {static}', '}', 'App --> University : university']
    diagram += MODEL['relationships']
    diagram += ['note "Черновик: 0..* факультетов/кафедр, декан 0..1.\\nvalidateReady(): факультетов >= 1, кафедр >= 1, декан = 1.\\nУ каждого исследователя всегда >= 1 кафедры." as Constraints', '@enduml', '']
    (ROOT / 'diagrams/02-class-model.puml').write_text('\n'.join(diagram))
    print(f'Generated {len(MODEL["classes"])} Java classes and class diagram.')

if __name__ == '__main__':
    main()
